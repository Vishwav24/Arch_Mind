"""Export project to Markdown format."""

import logging
from datetime import datetime

logger = logging.getLogger(__name__)


def generate_markdown_report(
    project: dict,
    requirements: list[dict],
    components: list[dict],
    connections: list[dict],
    decisions: list[dict],
    findings: list[dict],
    coverage_percent: float = 0.0,
) -> str:
    """Generate a comprehensive Markdown report."""
    sections = []

    # Title
    sections.append(f"# {project.get('title', 'Architecture Report')}")
    sections.append(f"\n*Generated by ArchMind AI on {datetime.utcnow().strftime('%Y-%m-%d %H:%M UTC')}*\n")

    if project.get("description"):
        sections.append(f"## Overview\n\n{project['description']}\n")

    # Requirements
    sections.append("## Requirements\n")
    if requirements:
        sections.append("| ID | Text | Type | Priority | Status | Provenance |")
        sections.append("|---|---|---|---|---|---|")
        for req in requirements:
            prov = "Source" if req.get("provenance") == "source" else "AI Assumption"
            sections.append(f"| {req.get('id', '')} | {req.get('text', '')[:100]} | {req.get('type', '')} | {req.get('priority', '')} | {req.get('status', '')} | {prov} |")
    else:
        sections.append("*No requirements extracted.*")
    sections.append("")

    # Architecture
    sections.append("## Architecture\n")
    if components:
        sections.append("### Architecture Diagram (Mermaid)\n")
        sections.append("```mermaid")
        sections.append("graph TD")
        for comp in components:
            cid = comp.get("id", "").replace("-", "_")
            name = comp.get("name", "").replace('"', "'")
            sections.append(f'    {cid}["{name}"]')
        for conn in connections:
            src = conn.get("from_component", conn.get("source", "")).replace("-", "_")
            tgt = conn.get("to_component", conn.get("target", "")).replace("-", "_")
            label = conn.get("protocol", "")
            if label:
                sections.append(f"    {src} -->|{label}| {tgt}")
            else:
                sections.append(f"    {src} --> {tgt}")
        sections.append("```\n")

        sections.append("### Components\n")
        sections.append("| ID | Name | Type | Description | Satisfies |")
        sections.append("|---|---|---|---|---|")
        for comp in components:
            satisfies = ", ".join(comp.get("satisfies", []))
            sections.append(f"| {comp.get('id', '')} | {comp.get('name', '')} | {comp.get('type', '')} | {comp.get('description', '')[:80]} | {satisfies} |")
    else:
        sections.append("*No architecture generated.*")
    sections.append("")

    # Decisions (ADRs)
    sections.append("## Architecture Decision Records (ADRs)\n")
    if decisions:
        for dec in decisions:
            sections.append(f"### {dec.get('id', '')}: {dec.get('title', '')}\n")
            sections.append(f"**Context:** {dec.get('context', '')}\n")
            sections.append(f"**Decision:** {dec.get('decision', '')}\n")
            sections.append(f"**Rationale:** {dec.get('rationale', '')}\n")
            if dec.get("alternatives"):
                sections.append("**Alternatives:**")
                for alt in dec["alternatives"]:
                    sections.append(f"- {alt}")
            if dec.get("trade_offs"):
                sections.append("\n**Trade-offs:**")
                for t in dec["trade_offs"]:
                    sections.append(f"- {t}")
            sections.append("")
    else:
        sections.append("*No ADRs generated.*")
    sections.append("")

    # Traceability Matrix
    sections.append("## Traceability Matrix\n")
    sections.append(f"**Coverage: {coverage_percent}%**\n")
    if requirements and components:
        comp_ids = [c.get("id", "") for c in components]
        header = "| Requirement | " + " | ".join(comp_ids) + " |"
        separator = "|---|" + "|".join(["---"] * len(comp_ids)) + "|"
        sections.append(header)
        sections.append(separator)
        for req in requirements:
            rid = req.get("id", "")
            cells = []
            for cid in comp_ids:
                comp = next((c for c in components if c.get("id") == cid), None)
                if comp and rid in comp.get("satisfies", []):
                    cells.append("Yes")
                else:
                    cells.append("-")
            sections.append(f"| {rid} | " + " | ".join(cells) + " |")
    sections.append("")

    # Validation
    sections.append("## Validation Report\n")
    if findings:
        for f in findings:
            severity = f.get("severity", "Medium")
            sections.append(f"- **[{severity}]** ({f.get('type', '')}) {f.get('explanation', '')}")
    else:
        sections.append("*No validation findings.*")
    sections.append("")

    return "\n".join(sections)

